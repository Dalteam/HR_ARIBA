CREATE FUNCTION public.parity_lookup(p_table text, p_name text) RETURNS integer
    LANGUAGE plpgsql
    AS $$
declare v integer;
begin
  if p_name is null or btrim(p_name) = '' then return null; end if;
  execute format('insert into public.%I(name) values ($1) on conflict (name) do update set name=excluded.name returning id',
                 p_table) into v using btrim(p_name);
  return v;
end $$;

-- employee_directory.employer/department/job_title -> the normalized references
CREATE FUNCTION public.parity_employee_refs() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  new.employer_id := public.parity_lookup('employers', new.employer);
  new.department_id := public.parity_lookup('departments', new.department);
  new.job_title_id := public.parity_lookup('job_titles', new.job_title);
  return new;
end $$;
CREATE TRIGGER parity_employee_refs BEFORE INSERT OR UPDATE ON public.employee_directory
    FOR EACH ROW EXECUTE FUNCTION public.parity_employee_refs();

-- work_locations.employer ('all' = every employer, i.e. no reference) -> employers
CREATE FUNCTION public.parity_location_employer() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  new.employer_id := case when new.employer in ('all', '') then null
                          else public.parity_lookup('employers', new.employer) end;
  return new;
end $$;
CREATE TRIGGER parity_location_employer BEFORE INSERT OR UPDATE ON public.work_locations
    FOR EACH ROW EXECUTE FUNCTION public.parity_location_employer();

-- attendance.emp_id <-> attendance.employee_id (either name may be written)
CREATE FUNCTION public.parity_attendance_employee() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  new.emp_id := coalesce(new.emp_id, new.employee_id);
  new.employee_id := coalesce(new.employee_id, new.emp_id);
  return new;
end $$;
CREATE TRIGGER parity_attendance_employee BEFORE INSERT OR UPDATE ON public.attendance
    FOR EACH ROW EXECUTE FUNCTION public.parity_attendance_employee();

