-- company_settings.shift_hours -> the normalized minutes column (whichever of the two a caller writes)
CREATE FUNCTION public.parity_shift_minutes() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  if new.shift_duration_minutes is not null then
    new.shift_hours := round(new.shift_duration_minutes / 60.0, 4);
  else
    new.shift_duration_minutes := round(coalesce(new.shift_hours, 8) * 60)::integer;
  end if;
  return new;
end $$;
CREATE TRIGGER parity_shift_minutes BEFORE INSERT OR UPDATE ON public.company_settings
    FOR EACH ROW EXECUTE FUNCTION public.parity_shift_minutes();

-- Only one open session (no time_out) per employee and day. The normalized database creates it as att_one_open_session
-- and the punch route relies on it for its "INSERT ... ON CONFLICT (employee_id,date) WHERE time_out IS NULL"; the
-- legacy table has no such constraint, so it is added here to give our code the shape it runs against in production.
CREATE UNIQUE INDEX parity_att_one_open_session ON public.attendance(employee_id, date) WHERE time_out IS NULL;

-- the HR and CEO approvers are the accounts of those roles (the normalized workflow_approvers table)
CREATE FUNCTION public.parity_sync_approver() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  if new.role in ('hr', 'ceo') and new.employee_id is not null then
    insert into public.workflow_approvers(stage, employee_id) values (new.role, new.employee_id)
    on conflict do nothing;
  end if;
  return new;
end $$;
CREATE TRIGGER parity_sync_approver AFTER INSERT OR UPDATE ON public.ariba_auth_accounts
    FOR EACH ROW EXECUTE FUNCTION public.parity_sync_approver();
