"""Compare the migrated database with the pre-migration source and check referential integrity.

Expected: every shared table keeps its row count (the migration only moves unexplainable rows into
backup tables), every employee keeps its legacy fields, the new lookup tables hold exactly the text
values of the legacy columns, and no soft reference points at a missing row.

Usage: backend\\.venv\\Scripts\\python.exe tools\\smoke\\db_verify.py [--src ariba_before_migration] [--dst ariba_src]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import psycopg

ROOT = Path(__file__).resolve().parents[2]  # repository root (this file lives in tools/smoke)

# Differences the migration is allowed to create, with the reason shown in the report.
EXPLAINED: dict[str, str] = {
    "employee_payrolls": "payroll rows of deleted employees are dropped (their months stay in payroll_archives_v2)",
    "workflow_actions": "one action row per migrated request stage is generated by the migration",
    "ariba_sessions": "sessions are not migrated (everyone signs in again)",
    "ariba_login_attempts": "login throttling counters are not migrated",
    "ariba_app_settings": "the migration adds the doc_sign_cfg and workflow_config defaults",
    "ariba_security_flags": "the migration adds the apply_invite_only and apply_invite_hours defaults",
}

# References the schema does not enforce (the legacy data had no foreign keys at all).
SOFT_REFERENCES = [
    ("employee_directory", "manager_id", "employee_directory", "employee_id"),
    ("attendance", "employee_id", "employee_directory", "employee_id"),
    ("employee_payrolls", "employee_id", "employee_directory", "employee_id"),
    ("leave_requests", "employee_id", "employee_directory", "employee_id"),
    ("permissions", "emp_id", "employee_directory", "employee_id"),
    ("ariba_auth_accounts", "employee_id", "employee_directory", "employee_id"),
    ("ariba_documents", "employee_id", "employee_directory", "employee_id"),
    ("workflow_requests", "employee_id", "employee_directory", "employee_id"),
    ("workflow_notifications", "recipient_employee_id", "employee_directory", "employee_id"),
    ("workflow_actions", "actor_employee_id", "employee_directory", "employee_id"),
    ("workflow_approvers", "employee_id", "employee_directory", "employee_id"),
]

EMPLOYEE_COLUMNS = ("name_ar", "name_en", "nationality", "iqama_no", "dob", "join_date", "manager_id", "active")


def connect(dbname: str, host: str, port: int, user: str) -> psycopg.Connection:
    return psycopg.connect(f"host={host} port={port} user={user} dbname={dbname}", autocommit=True)


def tables(db: psycopg.Connection) -> set[str]:
    rows = db.execute("SELECT table_name FROM information_schema.tables WHERE table_schema='public' "
                      "AND table_type='BASE TABLE'").fetchall()
    return {r[0] for r in rows}


def count(db: psycopg.Connection, table: str) -> int:
    return int(db.execute(f'SELECT count(*) FROM public."{table}"').fetchone()[0])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="ariba_before_migration")
    ap.add_argument("--dst", default="ariba_src")
    ap.add_argument("--host", default="localhost")
    ap.add_argument("--port", default=5432, type=int)
    ap.add_argument("--user", default="postgres")
    ap.add_argument("--out", default=str(ROOT / "_db_verify.txt"))
    args = ap.parse_args()

    lines: list[str] = [f"db verification: {args.dst} against {args.src}", ""]
    checks: list[tuple[str, bool, str]] = []

    def check(name: str, ok: bool, detail: str = "") -> None:
        checks.append((name, ok, detail))
        lines.append(f"{'PASS' if ok else 'FAIL'}  {name}" + (f"  {detail}" if detail else ""))

    with connect(args.src, args.host, args.port, args.user) as src, \
            connect(args.dst, args.host, args.port, args.user) as dst:
        shared = sorted(tables(src) & tables(dst))

        # 1. row counts per shared table
        drifted = []
        for table in shared:
            before, after = count(src, table), count(dst, table)
            if before == after:
                continue
            if table in EXPLAINED:
                lines.append(f"NOTE  {table}: {before} -> {after}  ({EXPLAINED[table]})")
            else:
                drifted.append(f"{table} {before}->{after}")
        check("every shared table kept its rows", not drifted, "; ".join(drifted))
        lines.append(f"      {len(shared)} shared tables compared")

        # 2. employees: same rows, same legacy columns, same legacy jsonb payload
        before = {r[0]: r[1:] for r in src.execute(
            f"SELECT employee_id,{','.join(EMPLOYEE_COLUMNS)},data FROM public.employee_directory").fetchall()}
        after = {r[0]: r[1:] for r in dst.execute(
            f"SELECT employee_id,{','.join(EMPLOYEE_COLUMNS)},data FROM public.employee_directory").fetchall()}
        lost = sorted(set(before) - set(after))
        changed = [eid for eid, row in before.items() if eid in after and after[eid] != row]
        check("every legacy employee exists in the migrated table", not lost, f"missing: {lost[:5]}" if lost else "")
        check("legacy employee columns and jsonb payload are unchanged", not changed,
              f"{len(changed)} differ, e.g. {changed[:5]}" if changed else f"{len(before)} employees")

        # 3. normalized lookups hold exactly the legacy text values
        for column, table in (("employer", "employers"), ("department", "departments"), ("job_title", "job_titles")):
            legacy = {r[0] for r in src.execute(
                f"SELECT DISTINCT {column} FROM public.employee_directory WHERE {column} IS NOT NULL").fetchall()}
            migrated = {r[0] for r in dst.execute(f"SELECT name FROM public.{table}").fetchall()}
            missing = sorted(legacy - migrated)
            check(f"{table} match the legacy «{column}» values", not missing,
                  f"missing: {missing[:5]}" if missing else f"{len(legacy)} values")

        # 4. attendance survives row for row (the old emp_id column is now employee_id)
        legacy_rows = set(src.execute("SELECT id,emp_id,date,time_in,time_out FROM public.attendance").fetchall())
        new_rows = set(dst.execute("SELECT id,employee_id,date,time_in,time_out FROM public.attendance").fetchall())
        check("attendance rows are identical", legacy_rows == new_rows,
              f"missing {len(legacy_rows - new_rows)}, extra {len(new_rows - legacy_rows)}")

        # 5. payroll rows only disappear with the employees they belong to (never for a live employee)
        orphan_rows = src.execute("""SELECT count(*) FROM public.employee_payrolls p
            WHERE NOT EXISTS (SELECT 1 FROM public.employee_directory d WHERE d.employee_id=p.employee_id)""").fetchone()[0]
        lost_payrolls = count(src, "employee_payrolls") - count(dst, "employee_payrolls")
        check("only payroll rows of deleted employees are dropped", lost_payrolls == orphan_rows,
              f"lost {lost_payrolls}, source orphans {orphan_rows}")
        kept = dst.execute("""SELECT count(*) FROM public.employee_payrolls p
            WHERE EXISTS (SELECT 1 FROM public.employee_directory d WHERE d.employee_id=p.employee_id)""").fetchone()[0]
        check("every payroll row of a live employee survived", kept == count(src, "employee_payrolls") - orphan_rows,
              f"{kept} rows")


        # 6. soft references (nothing in the legacy schema enforced them)
        for table, column, ref_table, ref_column in SOFT_REFERENCES:
            if table not in tables(dst):
                continue
            try:
                orphans = dst.execute(f"""SELECT count(*) FROM public."{table}" t WHERE t."{column}" IS NOT NULL
                    AND NOT EXISTS (SELECT 1 FROM public."{ref_table}" r
                                    WHERE r."{ref_column}"=t."{column}")""").fetchone()[0]
            except psycopg.Error as exc:  # the reference moved to another column name: report, do not crash
                lines.append(f"SKIP  {table}.{column} -> {ref_table}.{ref_column}  ({type(exc).__name__})")
                continue
            check(f"{table}.{column} -> {ref_table}.{ref_column} has no orphans", orphans == 0, f"{orphans} orphans")

        # 7. declared foreign keys are all validated
        unvalidated = dst.execute("""SELECT conrelid::regclass||'.'||conname FROM pg_constraint c
            JOIN pg_namespace n ON n.oid=c.connamespace
            WHERE c.contype='f' AND NOT c.convalidated AND n.nspname='public'""").fetchall()
        fk_count = dst.execute("""SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace
            WHERE c.contype='f' AND n.nspname='public'""").fetchone()[0]
        check("every foreign key is validated", not unvalidated,
              f"{fk_count} foreign keys; {[r[0] for r in unvalidated]}")

        # 8. duplicates the legacy data could hold
        for label, sql in (
            ("duplicate employee ids", "SELECT count(*) FROM (SELECT employee_id FROM public.employee_directory "
                                       "GROUP BY 1 HAVING count(*)>1) d"),
            ("duplicate usernames", "SELECT count(*) FROM (SELECT lower(username) FROM public.ariba_auth_accounts "
                                    "WHERE username IS NOT NULL GROUP BY 1 HAVING count(*)>1) d"),
            ("duplicate employee numbers", "SELECT count(*) FROM (SELECT data->>'empNo' "
                                           "FROM public.employee_directory WHERE data->>'empNo' IS NOT NULL "
                                           "GROUP BY 1 HAVING count(*)>1) d"),
            ("duplicate payroll months per employee", "SELECT count(*) FROM (SELECT employee_id,pay_year,pay_month "
                                                      "FROM public.employee_payrolls GROUP BY 1,2,3 "
                                                      "HAVING count(*)>1) d"),
        ):
            duplicates = dst.execute(sql).fetchone()[0]
            check(f"no {label}", duplicates == 0, f"{duplicates} found")

        # 9. required columns are populated
        blanks = dst.execute("""SELECT count(*) FROM public.employee_directory
            WHERE coalesce(btrim(employee_id),'')='' OR coalesce(btrim(name_ar),'')=''""").fetchone()[0]
        check("employee id and Arabic name are always filled", blanks == 0, f"{blanks} blank rows")

    failed = [name for name, ok, _ in checks if not ok]
    lines += ["", f"summary: checks={len(checks)}  failed={len(failed)}",
              "RESULT: " + ("FAIL" if failed else "OK")]
    text = "\n".join(lines)
    Path(args.out).write_text(text, encoding="utf-8")
    print(text)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())

