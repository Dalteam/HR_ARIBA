-- Bridge for the legacy-parity fixture (tests_canonical/test_legacy_parity.py).
--
-- schema.sql is the pre-normalization Supabase dump: employer/department/job title are text columns on
-- employee_directory, attendance is keyed by emp_id, the HR and CEO approvers are the constants hr_id/ceo_id of
-- workflow_requests, and the shift length is company_settings.shift_hours. The canonical code reads the normalized
-- shape instead (employers/departments/job_titles references, attendance.employee_id, workflow_approvers,
-- company_settings.shift_duration_minutes, the leave_types/permission_types/... lookups). This file derives that
-- shape from the legacy columns so both implementations can run side by side on the same database; the legacy
-- columns stay the source of truth and the legacy functions are untouched.

